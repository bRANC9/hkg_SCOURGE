class GateError(RuntimeError):
    """A hash pin, provenance check or completeness check failed."""


# ---------------------------------------------------------------------------
# Qt5 / moc constants
# ---------------------------------------------------------------------------

# QMetaObject is six pointers on x86-64 (Qt 5.0..5.15):
#   superdata, stringdata, data, static_metacall, relatedMetaObjects, extradata
QMETAOBJECT_SIZE = 6 * 8
OFF_SUPERDATA = 0
OFF_STRINGDATA = 8
OFF_DATA = 16
OFF_STATIC_METACALL = 24

# moc's stringdata literal array is an array of QArrayData (QByteArrayData).
# On x86-64: ref(4) size(4) alloc(4) pad(4) offset(8) == 24 bytes.
QBArrayData_SIZE = 24
QBD_OFF_SIZE = 4
QBD_OFF_OFFSET = 16

DATA_HEADER_WORDS = 14
MOC_REVISION = 7

METHOD_ACCESS_MASK = 0x03
METHOD_TYPE_MASK = 0x0C
METHOD_TYPE_NAMES = {0x00: "method", 0x04: "signal", 0x08: "slot", 0x0C: "constructor"}
METHOD_CLONED = 0x20

XML_IFACE_PREFIX = b'<interface name="com.lge.car.micom.'


@dataclass
class MocMethod:
    index: int
    name: str
    argc: int
    kind: str
    flags: int


@dataclass
class MocClass:
    name: str
    vaddr: str
    method_count: int
    signal_count: int
    static_metacall: str
    superdata: str
    methods: List[MocMethod] = field(default_factory=list)

    def slots(self) -> List[MocMethod]:
        return [m for m in self.methods if m.kind == "slot"]


# ---------------------------------------------------------------------------
# ELF helpers
# ---------------------------------------------------------------------------


class Image:
    """Address-space view over an ELF's loadable sections."""

    def __init__(self, path: Path):
        self.path = path
        self.fh = open(path, "rb")
        self.elf = ELFFile(self.fh)
        self.sections = []
        for sec in self.elf.iter_sections():
            if sec["sh_type"] == "SHT_NOBITS" or sec["sh_size"] == 0:
                continue
            if sec["sh_flags"] & 0x2:  # SHF_ALLOC
                self.sections.append((sec["sh_addr"], sec["sh_addr"] + sec["sh_size"], sec))
        self._relocs: Optional[Dict[int, int]] = None

    def _load_relocs(self) -> Dict[int, int]:
        """Collect R_X86_64_RELATIVE addends: where -> target vaddr.

        A malformed relocation section must not silently degrade into "found no
        meta-objects", so anything unexpected propagates.
        """
        relocs: Dict[int, int] = {}
        for sec in self.elf.iter_sections():
            if sec["sh_type"] not in ("SHT_RELA", "SHT_REL"):
                continue
            if not hasattr(sec, "iter_relocations"):
                continue
            for rel in sec.iter_relocations():
                if rel["r_info_type"] != 8:  # R_X86_64_RELATIVE
                    continue
                relocs[rel["r_offset"]] = rel["r_addend"]
        return relocs

    @property
    def relocs(self) -> Dict[int, int]:
        if self._relocs is None:
            self._relocs = self._load_relocs()
        return self._relocs

    def section_of(self, addr: int):
        for lo, hi, sec in self.sections:
            if lo <= addr < hi:
                return sec, addr - lo
        return None, None

    def read(self, addr: int, size: int) -> bytes:
        sec, off = self.section_of(addr)
        if sec is None:
            raise KeyError(f"0x{addr:x} not mapped")
        if off + size > sec["sh_size"]:
            raise KeyError(f"0x{addr:x}+{size} crosses section end")
        return sec.data()[off:off + size]

    def u32(self, addr: int) -> int:
        return struct.unpack_from("<I", self.read(addr, 4))[0]

    def i64(self, addr: int) -> int:
        return struct.unpack_from("<q", self.read(addr, 8))[0]

    def ptr(self, site: int) -> int:
        if site in self.relocs:
            return self.relocs[site]
        return struct.unpack_from("<Q", self.read(site, 8))[0]

    def literal(self, base: int, index: int) -> str:
        entry = base + QBArrayData_SIZE * index
        size = self.u32(entry + QBD_OFF_SIZE)
        offset = self.i64(entry + QBD_OFF_OFFSET)
        if size == 0:
            return ""
        if size > 4096:
            raise ValueError(f"implausible literal size {size} at 0x{entry:x}")
        return self.read(entry + offset, size).decode("utf-8", "replace")


IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def parse_metaobject(img: Image, site: int) -> Optional[MocClass]:
    """Parse a QMetaObject at `site`, or return None if it does not validate."""
    try:
        stringdata = img.ptr(site + OFF_STRINGDATA)
        data = img.ptr(site + OFF_DATA)
        metacall = img.ptr(site + OFF_STATIC_METACALL)
        superdata = img.ptr(site + OFF_SUPERDATA)
    except (KeyError, struct.error):
        return None
    if data == 0 or stringdata == 0:
        return None
    try:
        if img.u32(data) != MOC_REVISION:
            return None
        (revision, class_name_idx, classinfo_count, classinfo_data,
         method_count, method_data, prop_count, prop_data,
         enum_count, enum_data, ctor_count, ctor_data,
         flags, signal_count) = struct.unpack("<14I", img.read(data, DATA_HEADER_WORDS * 4))
    except (KeyError, struct.error):
        return None

    if method_count > 2000 or signal_count > method_count:
        return None
    try:
        class_name = img.literal(stringdata, class_name_idx)
    except (KeyError, ValueError, struct.error):
        return None
    if not IDENT_RE.match(class_name):
        return None

    cls = MocClass(
        name=class_name,
        vaddr=f"0x{site:x}",
        method_count=method_count,
        signal_count=signal_count,
        static_metacall=f"0x{metacall:x}",
        superdata=f"0x{superdata:x}" if superdata else "",
    )

    for i in range(method_count):
        entry = data + (method_data + 5 * i) * 4
        try:
            name_idx, argc, param_idx, tag, mflags = struct.unpack(
                "<5I", img.read(entry, 20))
        except (KeyError, struct.error):
            raise GateError(f"{class_name}: method table truncated at index {i}")
        if mflags & METHOD_CLONED:
            continue
        try:
            name = img.literal(stringdata, name_idx)
        except (KeyError, ValueError, struct.error) as exc:
            raise GateError(f"{class_name}: bad name literal at index {i}: {exc}")
        if not IDENT_RE.match(name):
            raise GateError(f"{class_name}: implausible method name {name!r}")
        if argc > 32:
            raise GateError(f"{class_name}.{name}: implausible argc {argc}")
        cls.methods.append(MocMethod(index=i, name=name, argc=argc,
                                     kind=METHOD_TYPE_NAMES.get(mflags & METHOD_TYPE_MASK,
                                                                "method"),
                                     flags=mflags))
    return cls


def find_metaobjects(img: Image) -> List[MocClass]:
    found: List[MocClass] = []
    for sec in img.elf.iter_sections():
        if sec["sh_type"] == "SHT_NOBITS" or sec["sh_size"] == 0:
            continue
        if sec.name not in (".data.rel.ro", ".data", ".rodata"):
            continue
        data = sec.data()
        base = sec["sh_addr"]
        for off in range(0, len(data) - QMETAOBJECT_SIZE + 1, 8):
            cls = parse_metaobject(img, base + off)
            if cls is not None and cls.method_count > 0:
                found.append(cls)
    return found


# ---------------------------------------------------------------------------
# Embedded interface XML -> D-Bus signatures
# ---------------------------------------------------------------------------


def _interface_roots(img: Image):
    """Yield ``(interface suffix, root element)`` for each embedded interface XML.

    qt5 embeds each interface as a NUL-terminated string literal in .rodata.
    Scanning for the interface prefix and walking to the terminator is stable
    across builds and keeps the signatures reproducible from the ELF alone.
    """
    for sec in img.elf.iter_sections():
        if sec.name not in (".rodata", ".data.rel.ro", ".data"):
            continue
        blob = sec.data()
        pos = 0
        while True:
            start = blob.find(XML_IFACE_PREFIX, pos)
            if start < 0:
                break
            end = blob.find(b"\x00", start)
            if end < 0:
                raise GateError(f"unterminated interface XML at 0x{start:x}")
            text = blob[start:end].decode("utf-8", "replace")
            pos = end
            try:
                root = ET.fromstring(text.strip())
            except ET.ParseError as exc:
                raise GateError(f"cannot parse embedded interface XML: {exc}")
            iface = root.get("name", "").split("com.lge.car.micom.")[-1]
            if iface not in IFACE_TITLES:
                raise GateError(f"unexpected interface name {root.get('name')!r}")
            yield iface, root


def embedded_signatures(img: Image) -> Dict[Tuple[str, str], Tuple[List[str], List[str]]]:
    """Parse the service's own method declarations and their D-Bus signatures."""
    sigs: Dict[Tuple[str, str], Tuple[List[str], List[str]]] = {}
    for iface, root in _interface_roots(img):
        for m in root:
            if m.tag != "method":
                continue
            ins = [a.get("type") for a in m if a.get("direction") == "in"]
            outs = [a.get("type") for a in m if a.get("direction") == "out"]
            sigs[(iface, m.get("name"))] = (ins, outs)
    if not sigs:
        raise GateError("no com.lge.car.micom interface XML found in the ELF")
    return sigs


def embedded_signals(img: Image) -> Dict[Tuple[str, str], List[str]]:
    """Parse the service's own signal declarations and their D-Bus out types."""
    sigs: Dict[Tuple[str, str], List[str]] = {}
    for iface, root in _interface_roots(img):
        for m in root:
            if m.tag != "signal":
                continue
            key = (iface, m.get("name"))
            if key in sigs:
                raise GateError(f"duplicate signal declaration {key[0]}.{key[1]}")
            sigs[key] = [a.get("type") for a in m if a.get("direction") == "out"]
    if not sigs:
        raise GateError("no com.lge.car.micom signal XML found in the ELF")
    return sigs


# ---------------------------------------------------------------------------
# Ghidra export: slot bodies -> opcodes
# ---------------------------------------------------------------------------

FUNC_HEADER_RE = re.compile(r"/\* ===== ([0-9a-f]+) (\S+) ===== \*/")
OPCODE_CALL_RE = re.compile(
    r"(FUN_[0-9a-f]+)\(\s*DAT_[0-9a-f]+\s*,\s*(0x[0-9a-f]+|\d+)", re.I)
CASE_RE = re.compile(r"^\s*case\s+(0x[0-9a-f]+|\d+)\s*:", re.I)
ACTIVATE_RE = re.compile(r"QMetaObject::activate")
CALL_RE = re.compile(r"\b(FUN_[0-9a-f]+)\s*\(")


@dataclass
class ExportFunction:
    addr: str
    name: str
    body: List[str]


def load_export(export_dir: Path) -> Dict[str, ExportFunction]:
    funcs: Dict[str, ExportFunction] = {}
    files = sorted(export_dir.glob("functions_*.c"))
    if not files:
        raise GateError(f"no functions_*.c under {export_dir}")
    for cfile in files:
        text = cfile.read_text(errors="replace").split("\n")
        marks = [(i, m) for i, line in enumerate(text)
                 if (m := FUNC_HEADER_RE.match(line))]
        for k, (i, m) in enumerate(marks):
            end = marks[k + 1][0] if k + 1 < len(marks) else len(text)
            funcs[m.group(1)] = ExportFunction(addr=m.group(1), name=m.group(2),
                                               body=text[i:end])
    if not funcs:
        raise GateError(f"export {export_dir} contains no function blocks")
    return funcs


def export_image_base(export_dir: Path) -> int:
    """Ghidra writes export addresses as ``vaddr + image_base`` (meta.json)."""
    meta = export_dir / "meta.json"
    if not meta.is_file():
        raise GateError(f"missing {meta}; cannot establish the export image base")
    try:
        raw = json.loads(meta.read_text()).get("image_base")
    except (ValueError, AttributeError) as exc:
        raise GateError(f"{meta}: unreadable image_base ({exc})")
    if raw is None:
        raise GateError(f"{meta}: no image_base")
    if isinstance(raw, str):
        try:
            value = int(raw, 0) if raw.lower().startswith("0x") else int(raw, 10)
        except ValueError:
            raise GateError(f"{meta}: image_base {raw!r} is neither hex nor decimal")
    elif isinstance(raw, int):
        value = raw
    else:
        raise GateError(f"{meta}: image_base has unsupported type {type(raw).__name__}")
    if value < 0:
        raise GateError(f"{meta}: negative image_base")
    return value


def metacall_slots(fn: ExportFunction, context: str) -> Dict[int, str]:
    """Map moc index -> slot function name; abort on ambiguity.

    A case that emits a signal calls QMetaObject::activate; a case that invokes
    a slot calls the slot function. Two distinct functions in one case means we
    cannot tell which is the slot, so we refuse rather than guess.
    """
    blocks: Dict[int, List[str]] = {}
    current: Optional[int] = None
    for line in fn.body:
        m = CASE_RE.match(line)
        if m:
            current = int(m.group(1), 0)
            blocks.setdefault(current, [])
            continue
        if current is not None:
            blocks[current].append(line)

    slots: Dict[int, str] = {}
    for index, lines in blocks.items():
        if any(ACTIVATE_RE.search(l) for l in lines):
            continue
        calls = {c.group(1) for l in lines if (c := CALL_RE.search(l))}
        if not calls:
            continue
        if len(calls) > 1:
            raise GateError(f"{context}: case {index} calls several functions "
                            f"{sorted(calls)}; cannot pick the slot")
        slots[index] = calls.pop()
    return slots


def slot_opcodes(fn: ExportFunction, context: str) -> List[int]:
    """All distinct opcodes a slot sends. Two different opcodes is an abort."""
    ops = {int(m.group(2), 0) for line in fn.body
           if (m := OPCODE_CALL_RE.search(line))}
    if len(ops) > 1:
        raise GateError(f"{context}: slot sends several distinct opcodes "
                        f"{sorted(hex(o) for o in ops)}")
    return sorted(ops)


# ---------------------------------------------------------------------------
# Gates
# ---------------------------------------------------------------------------


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def load_lock(path: Path, key: str) -> Optional[str]:
    if not path.is_file():
        return None
    for line in path.read_text().splitlines():
        m = re.match(rf'^{re.escape(key)}=["\']?([^"\'#\s]+)', line)
        if m:
            return m.group(1)
    return None


def gate_elf(path: Path, locks: Path, key: str) -> str:
    """Fail closed: no pin, unreadable lock file or mismatch all abort."""
    want = load_lock(locks, key)
    if want is None:
        raise GateError(f"no {key} pin in {locks}; refusing to derive from an "
                        f"unpinned binary (AGENTS.md rule 4, docs/09)")
    got = sha256_of(path)
    if got != want:
        raise GateError(f"ELF hash mismatch for {path}\n  want {want}\n  got  {got}")
    return got


def gate_export(export_dir: Path, elf_sha256: str) -> None:
    """The export directory is named bin_<sha256[:16]> by the exporter.

    Checking it prevents an opcode join against a decompilation of a different
    build that happens to resolve the same addresses.
    """
    expected = f"bin_{elf_sha256[:16]}"
    if export_dir.name != expected:
        raise GateError(f"export directory {export_dir.name!r} does not match the "
                        f"ELF (expected {expected!r}); refusing to join opcodes")


