"""Extract the micom D-Bus command table from a Gen5W ``micommanager_userspace``.

TARGET: Hyundai Ioniq 5 Gen5W_L (Linux x86-64), firmware
        NE_E.EUR.S5W_L.001.001.260128.

The head unit's micom service is a Qt5 program. Every command it exposes on
``com.lge.car.micom`` is a QObject slot generated by ``moc``, so the *names*,
the D-Bus signatures and the interface object paths live inside the ELF, and
the *opcodes* live as integer literals in the slot bodies. Neither is visible
to ``strings``.

Three sources are joined. Nothing is inferred from adjacency; a row is only
emitted when all applicable sources agree, and the tool aborts rather than
emit a partial table.

  1. **moc** (from the ELF): ``QMetaObject`` records in ``.data.rel.ro`` give
     ``(class, index, name, argc, kind)``.
  2. **embedded interface XML** (from the ELF): the service's own
     ``<interface name="com.lge.car.micom.…">`` blob gives the D-Bus
     signatures, so the In/Out columns are reproducible without a decompiler.
  3. **Ghidra export** (needs a decompilation): each ``qt_static_metacall``
     switch maps ``(class, index)`` to the slot function; the slot body holds
     ``FUN_xxx(manager, 0xNNNN, …)``.

Usage
-----
    python3 tools/micom/extract_commands.py moc     --elf PATH [--json OUT]
    python3 tools/micom/extract_commands.py table   --elf PATH --export DIR [--json OUT]
    python3 tools/micom/extract_commands.py signals --elf PATH [--notes JSON] [--json OUT]
    python3 tools/micom/extract_commands.py diff    --old ELF --new ELF [--json OUT]
    python3 tools/micom/extract_commands.py render  --json TABLE.json [--signals-json SIGNALS.json] --doc DOC.md
    python3 tools/micom/extract_commands.py callers --db INDEX.db [--json OUT]

Every command that reads an ELF is hash-gated against
``config/firmware_locks.env``. A missing pin, an export directory that does not
match the ELF's sha256, or an incomplete join is an **abort**, never a warning
(AGENTS.md rule 4, docs/09).
"""

