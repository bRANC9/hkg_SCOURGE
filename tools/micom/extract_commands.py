def _classes(elf: Path) -> List[MocClass]:
    return find_metaobjects(Image(elf))


def cmd_moc(args) -> int:
    sha = gate_elf(args.elf, args.locks, args.pin)
    classes = _classes(args.elf)
    classes.sort(key=lambda c: c.method_count, reverse=True)
    if args.json:
        redacted = []
        for c in classes:
            d = asdict(c)
            d["methods"] = [m for m in d["methods"]
                            if (c.name, m["index"]) not in WITHHELD_SLOTS]
            redacted.append(d)
        Path(args.json).write_text(json.dumps(redacted, indent=2) + "\n")
        print(f"wrote {args.json}", file=sys.stderr)
        return 0
    total_slots = 0
    for cls in classes:
        total_slots += len(cls.slots())
        print(f"{cls.name:44s} mo=0x{int(cls.vaddr, 16):08x} "
              f"methods={cls.method_count:3d} signals={cls.signal_count:3d} "
              f"slots={len(cls.slots()):3d} metacall={cls.static_metacall}")
    print(f"\n{len(classes)} metaobjects, {total_slots} slots")
    print(f"elf sha256 {sha}")
    return 0


IFACE_TITLES = {
    "ihu": "the head unit's own hardware, power and settings",
    "can": "vehicle bus bridging",
    "eng": "engineering, manufacturing and self-programming",
    "tmu": "telematics unit",
    "audio": "amplifier and volume",
    "radio": "tuner",
    "tmc": "traffic message channel",
    "hdr": "HD Radio",
}
IFACE_ORDER = ["ihu", "can", "eng", "tmu", "audio", "radio", "tmc", "hdr"]
INTERFACE_CLASSES = set(IFACE_TITLES) | {t + "adaptor" for t in IFACE_TITLES}

# Three service slots are implemented but absent from the interface XML and
# from every shipped caller. AGENTS.md rule 6 keeps undeclared, unused
# primitives out of published material, so they are excluded from every output
# this tool produces. They are identified here by (class, moc index) only; they
# still count toward the slot total so a partial join cannot hide them.
WITHHELD_SLOTS = {("ENG", 45), ("ENG", 46), ("IHU", 79)}


def _join(elf: Path, export: Path) -> Tuple[List[dict], List[MocClass], dict]:
    sha = gate_elf(elf, _LOCKS, "MICOM_MANAGER_SHA256")
    gate_export(export, sha)
    img = Image(elf)
    classes = find_metaobjects(img)
    sigs = embedded_signatures(img)
    funcs = load_export(export)
    image_base = export_image_base(export)

    rows: List[dict] = []
    expected = 0
    skipped: List[str] = []
    for cls in classes:
        if not cls.slots():
            continue
        if cls.name.lower() not in INTERFACE_CLASSES:
            # CMsgProcessor / CUartCommThread / replyDbusConnection are internal
            # helpers, not D-Bus interfaces, and dispatch outside the moc switch
            # (CMsgProcessor tail-calls an if-chain). They are out of scope and
            # are reported rather than silently dropped.
            skipped.append(cls.name)
            continue
        slots = resolve_metacall(funcs,
                                 f"{int(cls.static_metacall, 16) + image_base:08x}",
                                 f"{cls.name}::qt_static_metacall")
        for m in cls.slots():
            expected += 1
            if m.index not in slots:
                raise GateError(f"{cls.name}: slot {m.index} ({m.name}) has no "
                                f"metacall case")
            slot_name = slots[m.index]
            body = funcs.get(slot_name[4:])
            if body is None:
                raise GateError(f"{cls.name}.{m.name}: slot body {slot_name} is "
                                f"missing from the export")
            ops = slot_opcodes(body, f"{cls.name}.{m.name}")
            opcode = f"0x{ops[0]:04x}" if ops else ""
            ins, outs = sigs.get((cls.name.removesuffix("Adaptor").lower(), m.name), ([], []))
            rows.append({
                "class": cls.name,
                "index": m.index,
                "method": m.name,
                "kind": m.kind,
                "argc": m.argc,
                "args_in": ins,
                "args_out": outs,
                "slot": slot_name,
                "opcode": opcode,
                "metacall": cls.static_metacall,
            })

    if len(rows) != expected:
        raise GateError(f"joined {len(rows)} rows, expected {expected}")
    found = {c.name.lower() for c in classes}
    missing = INTERFACE_CLASSES - found
    if missing:
        raise GateError(f"interface classes missing from the ELF: {sorted(missing)}")
    if skipped:
        print(f"note: internal helper classes not joined (not D-Bus interfaces): "
              f"{', '.join(sorted(skipped))}", file=sys.stderr)
    rows.sort(key=lambda r: (r["class"], r["index"]))
    return rows, classes, sigs


def resolve_metacall(funcs: Dict[str, ExportFunction], addr_hex: str,
                     context: str, depth: int = 0) -> Dict[int, str]:
    """Locate the switch for a qt_static_metacall, following one tail-call.

    GCC sometimes splits ``qt_static_metacall`` so the exported function only
    checks the call type and tail-calls the real dispatcher (CMsgProcessor does
    exactly that at 0x13b460 -> 0x13b3b0). Follow a single unambiguous delegate
    rather than reporting the class as unjoinable.
    """
    fn = funcs.get(addr_hex)
    if fn is None:
        raise GateError(f"{context}: no export block at 0x{int(addr_hex, 16):x}")
    slots = metacall_slots(fn, context)
    if slots:
        return slots
    calls = {c.group(1) for line in fn.body if (c := CALL_RE.search(line))}
    calls.discard(fn.name)  # the header comment names the function itself
    if len(calls) == 1 and depth < 3:
        return resolve_metacall(funcs, calls.pop()[4:], context, depth + 1)
    raise GateError(f"{context}: no switch cases and no single delegate "
                    f"(candidates: {sorted(calls) or 'none'})")


def _visible(rows: List[dict]) -> List[dict]:
    return [r for r in rows if (r["class"], r["index"]) not in WITHHELD_SLOTS]


def cmd_table(args) -> int:
    rows, classes, sigs = _join(args.elf, args.export)
    opcodes = [r for r in rows if r["opcode"]]
    shown = _visible(rows)
    withheld = len(rows) - len(shown)
    print(f"{len(rows)} slot rows across {len(classes)} classes; "
          f"{len(opcodes)} carry an opcode, "
          f"{len({r['opcode'] for r in opcodes})} distinct; "
          f"{withheld} withheld under AGENTS.md rule 6", file=sys.stderr)
    if args.json:
        Path(args.json).write_text(json.dumps(shown, indent=2) + "\n")
        print(f"wrote {args.json}", file=sys.stderr)
        return 0
    for r in shown:
        print(f"{r['class']:16s} {r['index']:3d} {r['opcode']:>7s} "
              f"{r['kind']:6s} {r['method']}")
    return 0


def _load_signal_notes(path: Path) -> Dict[Tuple[str, str], Dict[str, str]]:
    """Load the inferred signal annotations and validate their shape.

    The notes are first-party interpretation (AGENTS.md rule 10): every signal
    must have one, and no note may name a signal the ELF does not declare.
    """
    try:
        raw = json.loads(path.read_text())
    except OSError as exc:
        raise GateError(f"{path}: cannot read signal notes ({exc})")
    except ValueError as exc:
        raise GateError(f"{path}: unreadable signal notes ({exc})")
    if not isinstance(raw, dict):
        raise GateError(f"{path}: signal notes must be an object keyed by interface")
    notes: Dict[Tuple[str, str], Dict[str, str]] = {}
    for iface, entries in raw.items():
        if iface.startswith("_"):
            continue
        if iface not in IFACE_TITLES:
            raise GateError(f"{path}: unknown interface {iface!r}")
        if not isinstance(entries, dict):
            raise GateError(f"{path}: {iface} must map signal names to notes")
        for name, note in entries.items():
            if not isinstance(note, dict):
                raise GateError(f"{path}: {iface}.{name} note must be an object")
            meaning = note.get("meaning")
            example = note.get("example", "—")
            if not isinstance(meaning, str) or not meaning.strip():
                raise GateError(f"{path}: {iface}.{name} has no meaning")
            if not isinstance(example, str) or not example.strip():
                raise GateError(f"{path}: {iface}.{name} has no example")
            notes[(iface, name)] = {"meaning": meaning.strip(),
                                    "example": example.strip()}
    return notes


def cmd_signals(args) -> int:
    """List the declared signals, optionally merging inferred annotations."""
    sha = gate_elf(args.elf, args.locks, args.pin)
    img = Image(args.elf)
    classes = find_metaobjects(img)
    declared = embedded_signals(img)
    notes: Dict[Tuple[str, str], Dict[str, str]] = {}
    if args.notes:
        notes = _load_signal_notes(args.notes)
        missing = set(declared) - set(notes)
        extra = set(notes) - set(declared)
        if missing:
            raise GateError(f"{args.notes}: missing note(s) for "
                            f"{', '.join(f'{i}.{n}' for i, n in sorted(missing))}")
        if extra:
            raise GateError(f"{args.notes}: note(s) for undeclared signal(s) "
                            f"{', '.join(f'{i}.{n}' for i, n in sorted(extra))}")

    moc: Dict[Tuple[str, str], List[int]] = {}
    for cls in classes:
        base = cls.name.lower()
        if base not in IFACE_TITLES:
            continue
        for m in cls.methods:
            if m.kind == "signal":
                moc.setdefault((base, m.name), []).append(m.argc)

    rows = []
    for (iface, name), outs in declared.items():
        argcs = moc.get((iface, name))
        if not argcs:
            raise GateError(f"{iface}.{name}: declared signal has no moc signal")
        if len(set(argcs)) != 1:
            raise GateError(f"{iface}.{name}: moc signal has inconsistent arity "
                            f"{sorted(set(argcs))}")
        argc = argcs[0]
        if argc != len(outs):
            raise GateError(f"{iface}.{name}: moc argc {argc} != XML out count "
                            f"{len(outs)}")
        note = notes.get((iface, name), {"meaning": "", "example": "—"})
        rows.append({
            "iface": iface,
            "name": name,
            "out": outs,
            "argc": argc,
            "meaning": note["meaning"],
            "example": note["example"],
        })

    moc_only = []
    for cls in classes:
        base = cls.name.lower()
        if base not in IFACE_TITLES:
            continue
        for m in cls.methods:
            if m.kind == "signal" and (base, m.name) not in declared:
                moc_only.append({"iface": base, "name": m.name, "argc": m.argc})

    rows.sort(key=lambda r: (IFACE_ORDER.index(r["iface"]), r["name"].lower()))
    moc_only.sort(key=lambda r: (IFACE_ORDER.index(r["iface"]), r["name"].lower()))
    with_payload = sum(1 for r in rows if r["out"])
    print(f"{len(rows)} declared signals ({with_payload} with a payload, "
          f"{len(rows) - with_payload} without); {len(moc_only)} moc-only "
          f"signal(s) outside the XML", file=sys.stderr)
    for r in moc_only:
        print(f"  moc-only: {r['iface']}.{r['name']} (argc={r['argc']})",
              file=sys.stderr)
    print(f"elf sha256 {sha}", file=sys.stderr)

    if args.json:
        Path(args.json).write_text(json.dumps(
            {"declared": rows, "moc_only": moc_only}, indent=2) + "\n")
        print(f"wrote {args.json}", file=sys.stderr)
        return 0
    for r in rows:
        print(f"{r['iface']:6s} {_fmt(r['out']):4s} {r['name']}"
              f"{'  # ' + r['meaning'] if r['meaning'] else ''}")
    return 0


def cmd_diff(args) -> int:
    old_sha = gate_elf(args.old, args.locks, args.old_pin)
    new_sha = gate_elf(args.new, args.locks, args.new_pin)
    old_classes = _classes(args.old)
    new_classes = _classes(args.new)
    old = {c.name: c for c in old_classes}
    new = {c.name: c for c in new_classes}

    # Resolve the withheld (class, index) pairs to names against both builds, so
    # the redaction filter survives an index shift and also covers a withheld
    # slot that a future build removes.
    withheld_names = {(c.name, m.name)
                      for classes in (old_classes, new_classes)
                      for c in classes for m in c.methods
                      if (c.name, m.index) in WITHHELD_SLOTS}

    def surface(cls):
        # Keyed by name: moc indices are not stable across builds, so an
        # index-keyed comparison reports every shifted slot as an add/remove.
        return {m.name: (m.kind, m.argc) for m in cls.methods
                if not (m.flags & METHOD_CLONED)}

    added: List[str] = []
    removed: List[str] = []
    changed: List[str] = []
    withheld = 0
    for name in sorted(set(old) | set(new)):
        if name.endswith("Adaptor"):
            continue  # the service class is authoritative; adaptors mirror it
        o = surface(old[name]) if name in old else {}
        n = surface(new[name]) if name in new else {}
        for meth in sorted(set(n) - set(o)):
            if (name, meth) in withheld_names:
                withheld += 1
                continue
            kind, argc = n[meth]
            added.append(f"{name}.{meth} ({kind}, argc={argc})")
        for meth in sorted(set(o) - set(n)):
            if (name, meth) in withheld_names:
                withheld += 1
                continue
            kind, argc = o[meth]
            removed.append(f"{name}.{meth} ({kind}, argc={argc})")
        for meth in sorted(set(o) & set(n)):
            if (name, meth) in withheld_names:
                continue
            if o[meth][1] != n[meth][1]:
                changed.append(f"{name}.{meth} {n[meth][0]} "
                               f"argc {o[meth][1]} -> {n[meth][1]}")

    def counts(table):
        svc = sum(len(c.slots()) for k, c in table.items()
                  if k.lower() in INTERFACE_CLASSES and not k.endswith("Adaptor"))
        hel = sum(len(c.slots()) for k, c in table.items()
                  if k.lower() not in INTERFACE_CLASSES)
        return svc, hel

    old_svc, old_hel = counts(old)
    new_svc, new_hel = counts(new)
    print(f"old: {old_svc} service slots (+{old_hel} helper)  sha256 {old_sha}")
    print(f"new: {new_svc} service slots (+{new_hel} helper)  sha256 {new_sha}")
    print(f"\nadded ({len(added)}):")
    for x in added:
        print(f"  + {x}")
    print(f"\nremoved ({len(removed)}):")
    for x in removed:
        print(f"  - {x}")
    print(f"\narity changed ({len(changed)}):")
    for x in changed:
        print(f"  ~ {x}")
    if withheld:
        print(f"\n({withheld} further change(s) withheld under AGENTS.md rule 6)")
    if args.json:
        Path(args.json).write_text(json.dumps(
            {"old_sha256": old_sha, "new_sha256": new_sha,
             "old_service_slots": old_svc, "new_service_slots": new_svc,
             "old_helper_slots": old_hel, "new_helper_slots": new_hel,
             "withheld": withheld,
             "added": added, "removed": removed, "changed": changed}, indent=2) + "\n")
    return 0


def _fmt(types: List[str]) -> str:
    return ", ".join(types) if types else "—"


def _replace_block(text: str, key: str, body: str) -> str:
    begin = f"<!-- BEGIN:{key} -->"
    end = f"<!-- END:{key} -->"
    i = text.find(begin)
    j = text.find(end)
    if i < 0 or j < 0 or j < i:
        raise GateError(f"document is missing the {begin} … {end} markers")
    return text[:i + len(begin)] + "\n\n" + body + "\n\n" + text[j:]


def _star(text: str) -> str:
    return text if text.endswith("*") else text + "*"


def _signal_table(rows: List[dict]) -> str:
    out = ["| Interface | Signal | Out | Meaning (inferred)* | "
           "Example payload (inferred)* |", "|---|---|---|---|---|"]
    for r in rows:
        try:
            iface = r["iface"]
            name = r["name"]
            outs = r["out"]
            meaning = r["meaning"].replace("|", "\\|")
            example = r["example"].replace("|", "\\|")
        except (KeyError, TypeError) as exc:
            raise GateError(f"signals JSON entry is not a signal row: {exc}")
        if not isinstance(outs, list) or not isinstance(meaning, str):
            raise GateError(f"{iface}.{name}: malformed signal row")
        if not meaning:
            raise GateError(f"{iface}.{name}: signal has no meaning annotation")
        sample = "—" if example == "—" else _star(example)
        out.append(f"| `{iface}` | `{name}` | {_fmt(outs)} | "
                   f"{_star(meaning)} | {sample} |")
    return "\n".join(out)


def cmd_render(args) -> int:
    rows = _visible(json.loads(Path(args.json).read_text()))
    doc = Path(args.doc)
    text = doc.read_text()

    for iface in IFACE_ORDER:
        sel = [r for r in rows if r["opcode"] and r["class"].lower() == iface]
        sel.sort(key=lambda r: (int(r["opcode"], 16), r["method"]))
        out = [f"### `com.lge.car.micom.{iface}` — {IFACE_TITLES[iface]}", "",
               f"{len(sel)} commands.", "",
               "| Opcode | Method | In | Out |", "|---|---|---|---|"]
        out += [f"| `0x{r['opcode'][2:]}` | `{r['method']}` | "
                f"{_fmt(r['args_in'])} | {_fmt(r['args_out'])} |" for r in sel]
        text = _replace_block(text, iface, "\n".join(out))

    sel = [r for r in rows if not r["opcode"] and not r["class"].endswith("Adaptor")]
    sel.sort(key=lambda r: (r["class"], r["index"]))
    out = ["| Interface | Method | In | Out |", "|---|---|---|---|"]
    out += [f"| `{r['class'].lower()}` | `{r['method']}` | "
            f"{_fmt(r['args_in'])} | {_fmt(r['args_out'])} |" for r in sel]
    text = _replace_block(text, "nonuart", "\n".join(out))

    if args.signals_json:
        data = json.loads(Path(args.signals_json).read_text())
        signals = data.get("declared") if isinstance(data, dict) else data
        if not isinstance(signals, list) or not signals:
            raise GateError(f"{args.signals_json}: no declared signals")
        text = _replace_block(text, "signals", _signal_table(signals))

    doc.write_text(text)
    print(f"rendered {doc}", file=sys.stderr)
    return 0


def cmd_callers(args) -> int:
    """Binaries that reference the service, from a full-export SQLite index."""
    import sqlite3

    rows = json.loads(Path(args.table).read_text())
    methods = sorted({r["method"] for r in rows if r["opcode"]})
    ifaces = list(IFACE_TITLES)
    con = sqlite3.connect(f"file:{args.db}?mode=ro", uri=True)
    paths = [r[0] for r in con.execute(
        "select distinct b.path from strings s join binaries b on b.id=s.binary_id "
        "where s.string like '%com.lge.car.micom%'")]
    marks = ",".join("?" * len(methods))
    out = []
    for p in paths:
        meth = sorted({r[0] for r in con.execute(
            f"select distinct s.string from strings s join binaries b "
            f"on b.id=s.binary_id where b.path=? and s.string in ({marks})",
            [p] + methods)})
        found = sorted({r[0].split("com.lge.car.micom.")[-1] for r in con.execute(
            "select distinct s.string from strings s join binaries b "
            "on b.id=s.binary_id where b.path=? and s.string like '%com.lge.car.micom.%'",
            [p])})
        ifs = [i for i in ifaces if i in found]
        if meth or ifs:
            out.append({"path": p, "interfaces": ifs, "methods": meth})
    out.sort(key=lambda x: (-len(x["methods"]), x["path"]))
    print(f"{len(out)} binaries reference the service and a known name "
          f"(of {len(paths)} that mention the bus name)", file=sys.stderr)
    if args.json:
        Path(args.json).write_text(json.dumps(out, indent=2) + "\n")
        print(f"wrote {args.json}", file=sys.stderr)
    else:
        for o in out:
            print(f"{o['path']:44s} {','.join(o['interfaces']) or '-':24s} {len(o['methods'])}")
    return 0


